assert.deepEqual(ranked.map(x=>[x.student_id,x.rank,x.score]),[['A',1,85],['B',1,85],['C',3,0],['D',null,null]]);
ranked=S.rank(people,[g('A','Math',4,5),g('A','English',90),g('B','Math',95)],'Math');
assert.equal(ranked[0].student_id,'B');assert.equal(ranked.find(p=>p.key==='A').subjects.English,90);
const weighted=S.rank(people,[g('A','Math',100),g('A','Math',100),g('A','English',0)]);
assert.equal(weighted[0].score,50);
assert(S.gradeErrors({studentKey:'Z',score:5,max:5,date:'2026-11-11',title:'Test',subject:'Math'},people).length);
